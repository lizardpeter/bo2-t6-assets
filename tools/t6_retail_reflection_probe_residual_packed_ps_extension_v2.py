#!/usr/bin/env python3
"""Exact packed-PS residual extension with regenerated/pinned target identities.

V2 preserves the v1 ownership and paired-VS proof unchanged, but removes its runtime
dependency on the never-committed TC2/TC1 target-set JSON. The exact 75 TC2 and 42
TC3 targets are first reconstructed and digest-verified by the shared residual target
census; a temporary TC2 compatibility file is supplied only to the v1 implementation.
"""
from __future__ import annotations
import argparse, importlib.util, json, tempfile
from pathlib import Path

HERE=Path(__file__).resolve().parent
V1=HERE/'t6_retail_reflection_probe_residual_packed_ps_extension_v1.py'
CENSUS=HERE/'t6_retail_reflection_probe_residual_target_census_v1.py'
OWNER=HERE/'t6_retail_reflection_probe_sphere_elec_packed_ps_probe_v2.py'
PAIRED=HERE/'t6_retail_reflection_probe_sphere_elec_paired_vs_probe_v2.py'

def load(path,name):
 s=importlib.util.spec_from_file_location(name,path);m=importlib.util.module_from_spec(s);assert s.loader;s.loader.exec_module(m);return m
_v1=load(V1,'residual_exact_v1_impl');_c=load(CENSUS,'residual_target_census_exact')

def __getattr__(name):return getattr(_v1,name)

def build(root:Path,owner_probe_path:Path,paired_probe_path:Path,base_path:Path,broad_path:Path,packed_vs_alias_path:Path):
 census=_c.build(root,base_path,broad_path)
 with tempfile.TemporaryDirectory(prefix='t6_residual_exact_') as td:
  target=Path(td)/'tc2_target_compat.json';_c.write_tc2_compat(census,target)
  d=_v1.build(root,owner_probe_path,paired_probe_path,base_path,broad_path,packed_vs_alias_path,target)
 d['format']='t6-retail-reflection-probe-residual-packed-ps-extension-v2'
 d['producer']='tools/t6_retail_reflection_probe_residual_packed_ps_extension_v2.py'
 src=dict(d.get('sources',{}));src['tc2Tc1TargetSet']='regenerated by tools/t6_retail_reflection_probe_residual_target_census_v1.py';src['residualTargetCensus']='tools/t6_retail_reflection_probe_residual_target_census_v1.py';d['sources']=src
 d['targetCensusSummary']=census['summary']
 d['correction']={'supersedesExecutionDependencyFrom':'tools/t6_retail_reflection_probe_residual_packed_ps_extension_v1.py','reason':'v1 expected an uncommitted TC2 target-set file; v2 reconstructs and digest-verifies the target populations before delegating to the identical exact packed-PS proof'}
 return d

def main():
 ap=argparse.ArgumentParser();ap.add_argument('--root',type=Path,required=True)
 ap.add_argument('--owner-probe',type=Path,default=OWNER);ap.add_argument('--paired-probe',type=Path,default=PAIRED)
 ap.add_argument('--base-verifier',type=Path,default=Path('tools/t6_retail_reflection_probe_texcoord2_texcoord1_v1.py'))
 ap.add_argument('--broad-verifier',type=Path,default=Path('tools/t6_retail_reflection_probe_texcoord3_texcoord1_v1.py'))
 ap.add_argument('--packed-vs-alias',type=Path,default=Path('manifests/render/T6_RETAIL_REFLECTION_PROBE_PACKED_VS_ALIAS_V1.json'))
 ap.add_argument('--out',type=Path,required=True);a=ap.parse_args();d=build(a.root,a.owner_probe,a.paired_probe,a.base_verifier,a.broad_verifier,a.packed_vs_alias);a.out.write_text(json.dumps(d,indent=2,sort_keys=True)+'\n');print(json.dumps(d['summary'],indent=2,sort_keys=True))
if __name__=='__main__':main()
